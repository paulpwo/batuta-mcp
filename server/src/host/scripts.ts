export const SCRIPTS: readonly string[] = Object.freeze([RUNNING_SCRIPT, MENU_SCRIPT, SAVE_AS_SCRIPT]);

/** `osascript -e <constant script> <variables...>`. A variable that could be read as an option (leading `-`), is empty or holds a NUL is refused. */
export function buildOsascriptArgs(script: string, variables: readonly string[]): string[] {
  for (const value of variables) {
    if (value.length === 0 || value.startsWith("-") || value.includes("\u0000")) throw new Error("host: refused an osascript argument that is empty, starts with - or holds a NUL");
  }
  return ["-e", script, ...variables];
}
