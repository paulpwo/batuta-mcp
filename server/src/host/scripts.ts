/**
 * The AppleScript sources of the host module (docs/04-host-automation.md sections 1 and 6).
 *
 * They are constants. Nothing is ever interpolated into them: the only variables (application
 * paths, the menu action id, the set path, the replace flag) arrive through `on run argv`.
 * The text is ASCII only (the ellipsis and the accented letter are built with `character id`),
 * uses no shell and no `run script`. Key events are forbidden everywhere except in SAVE_AS_SCRIPT, which has
 * exactly two, both inside `pressKey` (Cmd-Shift-G to open the Go to folder sheet, and Return to accept it);
 * `pressKey` sends nothing unless Live is the frontmost process and its Save panel is open (T9n,
 * docs/04-host-automation.md sections 1 and 6). Text is never typed: values are set through accessibility.
 * Every UI detail is an assumption [A] that the owner test in Live (T9) has to confirm.
 *
 * Errors are raised with fixed tokens and numbers (1001..1011) that host.ts maps to tool errors.
 */

/** Argv: absolute app paths. Prints the paths of those that are running, one per line. Starts nothing. */
export const RUNNING_SCRIPT: string = [
  "on run argv",
  "  set found to {}",
  "  repeat with candidate in argv",
  "    set candidatePath to candidate as text",
  "    if application candidatePath is running then set end of found to candidatePath",
  "  end repeat",
  "  set AppleScript's text item delimiters to linefeed",
  "  return found as text",
  "end run",
].join("\n");

